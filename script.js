// ==========================================================================
// THEME MANAGEMENT ENGINE
// ==========================================================================

function initTheme() {
    const savedTheme = localStorage.getItem("theme");
    const systemTheme = window.matchMedia("(prefers-color-scheme: light)").matches ? "light" : "dark";
    const activeTheme = savedTheme || systemTheme;
    setTheme(activeTheme);
}

function setTheme(theme) {
    document.documentElement.setAttribute("data-theme", theme);
    localStorage.setItem("theme", theme);
    
    if (themeIcon) {
        if (theme === "light") {
            themeIcon.className = "fa-solid fa-moon";
        } else {
            themeIcon.className = "fa-solid fa-sun";
        }
    }
}

if (themeToggleBtn) {
    themeToggleBtn.addEventListener("click", () => {
        const currentTheme = document.documentElement.getAttribute("data-theme");
        const newTheme = currentTheme === "light" ? "dark" : "light";
        setTheme(newTheme);
        showToast("تم تحويل مظهر الصفحة بنجاح!");
    });
}

// ==========================================================================
// DYNAMIC PORTFOLIO RENDERING, SEARCH & FILTERS
// ==========================================================================

function renderProjects() {
    if (!projectsGrid) return;
    
    projectsGrid.innerHTML = "";
    
    const filteredProjects = projectsData.filter(project => {
        const matchesCategory = currentCategory === "all" || project.category === currentCategory;
        
        const matchesSearch = project.title.toLowerCase().includes(searchQuery.toLowerCase()) ||
                              project.description.toLowerCase().includes(searchQuery.toLowerCase()) ||
                              project.tags.some(tag => tag.toLowerCase().includes(searchQuery.toLowerCase()));
                              
        return matchesCategory && matchesSearch;
    });
    
    if (filteredProjects.length === 0) {
        projectsGrid.innerHTML = `
            <div class="empty-state">
                <i class="fa-solid fa-magnifying-glass-minus"></i>
                <h3>لم نعثر على أي نتائج!</h3>
                <p>تأكد من كتابة أحرف البحث بشكل صحيح أو جرب تصنيفات أخرى.</p>
            </div>
        `;
        return;
    }
    
    filteredProjects.forEach((project, index) => {
        const card = document.createElement("div");
        card.className = "glass-container project-card fade-in-up";
        card.style.animationDelay = `${index * 0.08}s`;
        
        const tagsHtml = project.tags.map(tag => `<span class="project-tag">${tag}</span>`).join("");
        
        card.innerHTML = `
            <div class="project-image-container">
                <img src="${project.imageUrl}" alt="${project.title}" class="project-img" onerror="handleImageError(this)">
            </div>
            <div class="project-info">
                <div class="project-tags">
                    ${tagsHtml}
                </div>
                <h3 class="project-name">${project.title}</h3>
                <p class="project-desc">${project.description}</p>
                <div class="project-actions">
                    <button class="btn btn-primary" onclick="openGallery(${project.id})">
                        <i class="fa-regular fa-images"></i> عرض الصور
                    </button>
                    <button class="btn btn-secondary" onclick="openVideo(${project.id})">
                        <i class="fa-solid fa-circle-play"></i> عرض الفيديو
                    </button>
                </div>
            </div>
        `;
        
        projectsGrid.appendChild(card);
    });
}

function handleImageError(img) {
    const container = img.parentElement;
    container.innerHTML = `
        <div class="project-image-fallback">
            <i class="fa-solid fa-code"></i>
            <span>Project Preview</span>
        </div>
    `;
}

if (searchInput) {
    searchInput.addEventListener("input", (e) => {
        searchQuery = e.target.value.trim();
        renderProjects();
    });
}

if (filterButtons) {
    filterButtons.forEach(button => {
        button.addEventListener("click", () => {
            filterButtons.forEach(btn => btn.classList.remove("active"));
            button.classList.add("active");
            currentCategory = button.getAttribute("data-filter");
            renderProjects();
        });
    });
}

// ==========================================================================
// IMAGE LIGHTBOX MODAL SYSTEM
// ==========================================================================

function openGallery(projectId) {
    const project = projectsData.find(p => p.id === projectId);
    if (!project || !project.gallery || project.gallery.length === 0) {
        showToast("لا توجد صور متوفرة لهذا المشروع حالياً.");
        return;
    }
    
    activeGallery = project.gallery;
    activeImageIndex = 0;
    
    if (modalProjectTitle) {
        modalProjectTitle.textContent = project.title;
    }
    
    updateModalImage();
    renderThumbnails();
    
    if (galleryModal) {
        galleryModal.classList.add("show");
        document.body.style.overflow = "hidden";
    }
}

function closeGallery() {
    if (galleryModal) {
        galleryModal.classList.remove("show");
        document.body.style.overflow = "";
    }
}

function updateModalImage() {
    if (!modalActiveImg || !modalImgCaption || activeGallery.length === 0) return;
    
    const activeItem = activeGallery[activeImageIndex];
    modalActiveImg.style.opacity = 0.2;
    
    setTimeout(() => {
        modalActiveImg.src = activeItem.src;
        modalImgCaption.textContent = activeItem.caption;
        modalActiveImg.style.opacity = 1;
        
        const thumbs = modalThumbnails ? modalThumbnails.querySelectorAll(".thumb-item") : [];
        thumbs.forEach((thumb, idx) => {
            if (idx === activeImageIndex) {
                thumb.classList.add("active");
                thumb.scrollIntoView({ behavior: 'smooth', block: 'nearest', inline: 'center' });
            } else {
                thumb.classList.remove("active");
            }
        });
    }, 150);
}

function renderThumbnails() {
    if (!modalThumbnails) return;
    modalThumbnails.innerHTML = "";
    
    activeGallery.forEach((item, index) => {
        const thumb = document.createElement("div");
        thumb.className = `thumb-item ${index === activeImageIndex ? 'active' : ''}`;
        thumb.innerHTML = `<img src="${item.src}" alt="Thumbnail">`;
        
        thumb.addEventListener("click", () => {
            activeImageIndex = index;
            updateModalImage();
        });
        
        modalThumbnails.appendChild(thumb);
    });
}

if (modalPrevBtn) {
    modalPrevBtn.addEventListener("click", () => {
        if (activeGallery.length === 0) return;
        activeImageIndex = (activeImageIndex - 1 + activeGallery.length) % activeGallery.length;
        updateModalImage();
    });
}

if (modalNextBtn) {
    modalNextBtn.addEventListener("click", () => {
        if (activeGallery.length === 0) return;
        activeImageIndex = (activeImageIndex + 1) % activeGallery.length;
        updateModalImage();
    });
}

if (modalClose) {
    modalClose.addEventListener("click", closeGallery);
}

if (galleryModal) {
    galleryModal.addEventListener("click", (e) => {
        if (e.target === galleryModal) {
            closeGallery();
        }
    });
}

// ==========================================================================
// VIDEO PREVIEW MODAL SYSTEM
// ==========================================================================

function openVideo(projectId) {
    const project = projectsData.find(p => p.id === projectId);
    if (!project) return;
    
    if (videoModalProjectTitle) {
        videoModalProjectTitle.textContent = `فيديو معاينة | ${project.title}`;
    }
    
    if (modalVideo && videoFallback) {
        // Set src directly on the video element for maximum cross-browser compatibility
        modalVideo.src = project.videoUrl || "";
        modalVideo.load();
        
        modalVideo.style.display = "none";
        videoFallback.style.display = "flex";
        
        // Try playing the video
        modalVideo.play().then(() => {
            modalVideo.style.display = "block";
            videoFallback.style.display = "none";
        }).catch(err => {
            console.log("Video playback failed or file not found, displaying fallback card:", err);
            modalVideo.style.display = "none";
            videoFallback.style.display = "flex";
        });
    }
    
    if (videoModal) {
        videoModal.classList.add("show");
        document.body.style.overflow = "hidden";
    }
}

function closeVideo() {
    if (modalVideo) {
        modalVideo.pause();
    }
    if (videoModal) {
        videoModal.classList.remove("show");
        document.body.style.overflow = "";
    }
}

if (videoModalClose) {
    videoModalClose.addEventListener("click", closeVideo);
}

if (videoModal) {
    videoModal.addEventListener("click", (e) => {
        if (e.target === videoModal) {
            closeVideo();
        }
    });
}

// Keyboard Listeners
window.addEventListener("keydown", (e) => {
    if (e.key === "Escape") {
        closeGallery();
        closeVideo();
    }
    
    if (galleryModal && galleryModal.classList.contains("show")) {
        if (e.key === "ArrowLeft") {
            if (activeGallery.length === 0) return;
            activeImageIndex = (activeImageIndex + 1) % activeGallery.length;
            updateModalImage();
        } else if (e.key === "ArrowRight") {
            if (activeGallery.length === 0) return;
            activeImageIndex = (activeImageIndex - 1 + activeGallery.length) % activeGallery.length;
            updateModalImage();
        }
    }
});

// Expose functions globally for inline onclick
window.openGallery = openGallery;
window.openVideo = openVideo;

// ==========================================================================
// TOAST MESSAGES SYSTEM & INTERACTIONS
// ==========================================================================

function showToast(message) {
    if (!toastContainer) return;
    
    const toast = document.createElement("div");
    toast.className = "toast";
    toast.innerHTML = `
        <i class="fa-solid fa-circle-check"></i>
        <span>${message}</span>
    `;
    
    toastContainer.appendChild(toast);
    
    setTimeout(() => {
        toast.classList.add("show");
    }, 50);
    
    setTimeout(() => {
        toast.classList.remove("show");
        setTimeout(() => {
            toast.remove();
        }, 400);
    }, 3000);
}

// Global copyEmail for premium footer
function copyEmail(el) {
    const emailText = el.querySelector(".email-text").textContent.trim();
    navigator.clipboard.writeText(emailText).then(() => {
        el.classList.add("copied");
        const actionSpan = el.querySelector(".pf__email-action span:last-child");
        if (actionSpan) actionSpan.textContent = "تم النسخ ✓";
        showToast("تم نسخ البريد الإلكتروني للحافظة!");
        setTimeout(() => {
            el.classList.remove("copied");
            if (actionSpan) actionSpan.textContent = "نسخ";
        }, 2500);
    }).catch(err => {
        console.error("Could not copy email", err);
    });
}
window.copyEmail = copyEmail;

if (emailBox) {
    emailBox.addEventListener("click", () => {
        copyEmail(emailBox);
    });
}

if (downloadCvBtn) {
    downloadCvBtn.addEventListener("click", (e) => {
        showToast("جاري إعداد وتحميل السيرة الذاتية (CV)...");
    });
}

